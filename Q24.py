# Solution
str_a = "Hello"
str_b = "World"

# Concatenation (+)
concat_result = str_a + " " + str_b

# Repetition (*)
repeat_result = "Python! " * 3

print("Concatenation (+):", concat_result)
print("Repetition (*)   :", repeat_result)
