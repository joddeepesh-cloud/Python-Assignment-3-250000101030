# Solution
languages = ["C", "C++", "Java", "Python", "Ruby"]
print("Original list:", languages)

# Popping element at index 2 ('Java')
removed_item = languages.pop(2)
print("Removed item:", removed_item)
print("List after pop(2):", languages)
