# Solution
words = ["Python", "is", "simple", "yet", "powerful"]
joined_str = " ".join(words)
hyphen_joined = "-".join(words)

print("Words list  :", words)
print("Space-joined :", joined_str)
print("Hyphen-joined:", hyphen_joined)
