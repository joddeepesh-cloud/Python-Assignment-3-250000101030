# Solution
numbers = [42, 11, 88, 23, 65, 9, 74]
print("Original List:", numbers)

# Ascending order
numbers.sort()
print("Ascending Sort :", numbers)

# Descending order
numbers.sort(reverse=True)
print("Descending Sort:", numbers)
